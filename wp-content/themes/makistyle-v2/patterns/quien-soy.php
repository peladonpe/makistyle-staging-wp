<p class="has-text-align-center color-blanco diez-lineas has-blanco-color has-text-color has-link-color has-medium-font-size" id="biografia">          Nací en Burriana (Castellón) en 1987, en una familia con una fuerte
          conexión con la música. Desde pequeño respiré ese ambiente musical,
          especialmente gracias a mi hermano mayor, que ya formaba parte de la
          banda de música del pueblo. A los 8 años, mis padres me apuntaron al
          conservatorio, donde elegí tocar la trompeta, un instrumento que hacía
          falta en la banda local. Durante años seguí el camino clásico:
          conciertos, pasodobles, obras tradicionales… hasta que llegué al
          segundo de grado medio. Fue entonces cuando me di cuenta de que,
          aunque valoraba esa formación, ese tipo de música no era lo mío. Lo
          mío era algo más hard. En mi adolescencia descubrí el universo del
          hardcore, makina y remember, la música que me hacía vibrar de verdad.
          Empecé grabando y mezclando cintas con radiocasetes, de forma muy
          rudimentaria pero con una creatividad que ya apuntaba hacia algo más
          grande. Aquello no era solo una curiosidad: estaba empezando una
          pasión. El gran cambio llegó cuando conocí el newstyle gracias a las
          sesiones de la discoteca La Masía. Fue una revelación. A partir de ese
          momento, empecé a frecuentar templos del sonido como Masía, Pirámide,
          Manssion, Central o Pont Aeri, y me sumergí de lleno en esa cultura. A
          los 18 años, por pura curiosidad, instalé Fruity Loops en mi
          ordenador. Y ahí empezó todo. Descubrí un mundo, un hobby y una
          pasión: la producción musical. Desde entonces he experimentado con
          distintos secuenciadores como Cubase, Studio One y Ableton, formándome
          de manera prácticamente autodidacta, en una época donde no existía la
          cantidad de recursos que hay hoy. Durante un tiempo también exploré el
          mundo del DJ, utilizando CDJ, Traktor y Virtual DJ, pero pronto
          comprendí que mi verdadera motivación no era pinchar en cabinas, sino
          crear música desde cero y ver cómo otras personas disfrutan bailando
          lo que he creado desde el estudio de mi casa. Hoy, como productor bajo
          el nombre Makistyle, canalizo todas esas influencias y vivencias en
          cada tema que compongo. Mi objetivo es claro: hacer música con alma,
          con fuerza, con identidad, y compartir esa energía con el mundo.</p>
